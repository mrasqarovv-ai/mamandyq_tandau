#!/usr/bin/env python3
"""Build the server scoring bank from source-verified practice questions/keys."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    quizzes = json.loads((ROOT/'data/quizzes.json').read_text())['quizzes']
    keys = json.loads((ROOT/'data/practice-keys.json').read_text())
    for quiz in quizzes:
        mapping = keys[quiz['id']]
        if set(mapping) != {q['id'] for q in quiz['questions']}:
            raise ValueError(f"Incomplete official key: {quiz['id']}")
        for question in quiz['questions']:
            answer = mapping[question['id']]
            if answer not in {x['id'] for x in question['options']}:
                raise ValueError(f"Invalid official answer: {quiz['id']}/{question['id']}")
            question['correctOptionId'] = answer
    target = ROOT/'worker/src/quiz-bank.js'
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text('// Generated by tools/build_quiz_bank.py from verified official material.\n'
                      'export const quizzes = '+json.dumps(quizzes,ensure_ascii=False,indent=2)+';\n')
    print(f'Built {len(quizzes)} quizzes / {sum(len(q["questions"]) for q in quizzes)} verified questions.')


if __name__ == '__main__':
    main()
